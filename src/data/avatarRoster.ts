export function getAvatarRosterPreset(id: string): AvatarRosterPreset | undefined {
  return avatarRoster.find((preset) => preset.id === id);
}

export function getAvatarRosterPresetForDesign(
  design: Pick<SipAvatarDesign, "rosterCharacterId" | "beverageCategory" | "presentation">
): AvatarRosterPreset {
  const direct = getAvatarRosterPreset(design.rosterCharacterId);
  if (direct) return direct;

  const categoryKey: AvatarRosterCategoryKey =
    design.beverageCategory === "wine"
      ? "wine"
      : design.beverageCategory === "beer"
        ? "beer"
        : design.beverageCategory === "spirits" || design.beverageCategory === "cocktails"
          ? "spirits"
          : design.beverageCategory === "coffee"
            ? "coffee"
            : design.beverageCategory === "tea"
              ? "tea"
              : "water";
  const adultPresentation: AvatarRosterPresentation = design.presentation === "masculine" ? "man" : "woman";

  return (
    avatarRoster.find(
      (preset) => preset.categoryKey === categoryKey && preset.adultPresentation === adultPresentation
    ) ?? avatarRoster[0]
  );
}
